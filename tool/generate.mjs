// Generates packages/syntax_darts/lib/langs/*.dart and lib/themes/*.dart from the
// tm-grammars and tm-themes npm packages (the same data Shiki ships).
//
// Each grammar and theme becomes a `const` Dart value in its own library,
// so apps only pay for what they import.

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { grammars } from 'tm-grammars'
import { themes } from 'tm-themes'
import { LANGS, THEMES, camel } from './bundle.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const pkg = path.join(here, '..', 'packages', 'syntax')
const modules = path.join(here, 'node_modules')
const readJson = (...parts) => JSON.parse(fs.readFileSync(path.join(modules, ...parts), 'utf8'))
const version = (name) => readJson(name, 'package.json').version

/** Encodes a JSON value as a Dart const literal. */
function dart(value, indent = '') {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'boolean' || typeof value === 'number') return String(value)
  if (typeof value === 'string') return dartString(value)
  const next = indent + '  '
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    return `[\n${value.map((v) => next + dart(v, next)).join(',\n')},\n${indent}]`
  }
  const entries = Object.entries(value)
  if (entries.length === 0) return '{}'
  return `{\n${entries.map(([k, v]) => `${next}${dartString(k)}: ${dart(v, next)}`).join(',\n')},\n${indent}}`
}

function dartString(s) {
  let out = "'"
  for (const ch of s) {
    const cp = ch.codePointAt(0)
    if (ch === '\\') out += '\\\\'
    else if (ch === "'") out += "\\'"
    else if (ch === '$') out += '\\$'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\t') out += '\\t'
    else if (cp < 0x20 || cp > 0x7e) out += `\\u{${cp.toString(16)}}`
    else out += ch
  }
  return out + "'"
}

const header = (source, license) =>
  `// GENERATED by tool/generate.mjs. Do not edit.\n` +
  `// Source: ${source}\n` +
  (license ? `// License: ${license}\n` : '') +
  `// ignore_for_file: prefer_single_quotes, lines_longer_than_80_chars\n`

// File extensions tm-grammars doesn't list as aliases, so that
// Highlighter.languageForPath finds them.
const EXTRA_ALIASES = { diff: ['patch'], html: ['htm'], xml: ['svg'] }

function writeLangs() {
  const dir = path.join(pkg, 'lib', 'langs')
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
  const exports = []
  for (const name of LANGS) {
    const meta = grammars.find((g) => g.name === name)
    if (!meta) throw new Error(`Unknown grammar ${name}`)
    const grammar = readJson('tm-grammars', 'grammars', `${name}.json`)
    const id = `${camel(name)}Language`
    const file = `${name}.dart`
    fs.writeFileSync(
      path.join(dir, file),
      header(meta.source, meta.license) +
        `import 'package:syntax_darts/syntax.dart' show Language;\n\n` +
        `/// ${meta.displayName} (\`${meta.scopeName}\`).\n` +
        `const ${id} = Language(\n` +
        `  name: ${dartString(name)},\n` +
        `  scopeName: ${dartString(meta.scopeName)},\n` +
        `  displayName: ${dartString(meta.displayName)},\n` +
        `  aliases: ${dart([...new Set([...(meta.aliases ?? []), ...(EXTRA_ALIASES[name] ?? [])])], '  ')},\n` +
        `  grammar: <String, Object?>${dart(grammar, '  ')},\n` +
        `);\n`,
    )
    exports.push({ file, id })
  }
  writeIndex(dir, 'Language', 'bundledLanguages', exports)
}

function writeThemes() {
  const dir = path.join(pkg, 'lib', 'themes')
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
  const exports = []
  for (const name of THEMES) {
    const meta = themes.find((t) => t.name === name)
    if (!meta) throw new Error(`Unknown theme ${name}`)
    const theme = readJson('tm-themes', 'themes', `${name}.json`)
    // Keep only what highlighting uses; editor `colors` stay for widgets.
    const { semanticTokenColors, semanticHighlighting, ...json } = theme
    const id = `${camel(name)}Theme`
    const file = `${name.replace(/-/g, '_')}.dart`
    fs.writeFileSync(
      path.join(dir, file),
      header(meta.source, meta.license) +
        `import 'package:syntax_darts/syntax.dart' show SyntaxTheme;\n\n` +
        `/// ${meta.displayName}.\n` +
        `const ${id} = SyntaxTheme(\n` +
        `  name: ${dartString(name)},\n` +
        `  json: <String, Object?>${dart(json, '  ')},\n` +
        `);\n`,
    )
    exports.push({ file, id })
  }
  writeIndex(dir, 'SyntaxTheme', 'bundledThemes', exports)
}

function writeIndex(dir, type, listName, exports) {
  const lines = [
    '// GENERATED by tool/generate.mjs. Do not edit.',
    '//',
    '// Importing this library pulls in every bundled entry. Import',
    '// individual files instead to keep app size down.',
    `import 'package:syntax_darts/syntax.dart' show ${type};`,
    '',
    ...exports.map(({ file }) => `import '${file}';`),
    '',
    ...exports.map(({ file }) => `export '${file}';`),
    '',
    `/// Every bundled entry, keyed by name.`,
    `const ${listName} = <String, ${type}>{`,
    ...exports.map(({ file, id }) => `  ${dartString(file.replace('.dart', '').replace(/_/g, '-'))}: ${id},`),
    '};',
    '',
  ]
  fs.writeFileSync(path.join(dir, 'all.dart'), lines.join('\n'))
}

/**
 * Notices for bundled files that the upstream NOTICE does not cover.
 * Each needs its license checked by hand at the source.
 */
const EXTRA_NOTICES = {
  'tm-grammars': {
    // textmate/yaml.tmbundle has no LICENSE file; its README grants this.
    yaml: [
      'Files:   yaml.json',
      'License: https://github.com/textmate/yaml.tmbundle#license',
      '---------------------------------------------------------------------------------------------------------',
      'Permission to copy, use, modify, sell and distribute this',
      'software is granted. This software is provided "as is" without',
      'express or implied warranty, and with no claim as to its',
      'suitability for any purpose.',
    ].join('\n'),
  },
}

/**
 * Keeps only the upstream NOTICE sections that cover bundled files. Each
 * section starts after a line of `=` and names its files on a `Files:` line.
 */
function bundledNotice(pkgName, bundled) {
  const text = fs.readFileSync(path.join(modules, pkgName, 'NOTICE'), 'utf8')
  const [header, ...sections] = text.split(/^=+$/m)
  const covered = new Set()
  const kept = sections.filter((section) => {
    const files = /^Files:\s*(.+)$/m.exec(section)?.[1]
    if (!files) return false
    const names = files.split(',').map((f) => f.trim().replace(/\.json$/, ''))
    const hits = names.filter((n) => bundled.includes(n))
    hits.forEach((n) => covered.add(n))
    return hits.length > 0
  })
  const extras = EXTRA_NOTICES[pkgName] ?? {}
  for (const [name, section] of Object.entries(extras)) {
    if (bundled.includes(name) && !covered.has(name)) {
      kept.push(section)
      covered.add(name)
    }
  }
  const missing = bundled.filter((n) => !covered.has(n))
  if (missing.length) throw new Error(`${pkgName} NOTICE has no section for: ${missing.join(', ')}`)
  const rule = '='.repeat(105)
  return `${header.trim()}\n\n${kept.map((s) => `${rule}\n${s.trim()}\n`).join('\n')}`
}

function writeNotice() {
  const notice =
    `syntax bundles TextMate grammars from tm-grammars@${version('tm-grammars')} and\n` +
    `themes from tm-themes@${version('tm-themes')} (https://github.com/shikijs/textmate-grammars-themes).\n` +
    `Each generated file names its upstream source and license. The notices\n` +
    `for the bundled grammars and themes follow.\n\n` +
    bundledNotice('tm-grammars', LANGS) +
    '\n\n' +
    bundledNotice('tm-themes', THEMES) +
    '\n'
  fs.writeFileSync(path.join(pkg, 'NOTICE'), notice)
}

writeLangs()
writeThemes()
writeNotice()
// Keep generated code in the formatter's style so CI format checks pass.
execFileSync('dart', ['format', 'lib/langs', 'lib/themes'], { cwd: pkg, stdio: 'ignore' })
console.log(`Generated ${LANGS.length} languages and ${THEMES.length} themes.`)
